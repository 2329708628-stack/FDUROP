# -*- coding: utf-8 -*-
"""
数据清洗
============
1. 删除元信息（摘要/作者/关键词/基金项目/作者简介/DOI/知网/页眉/页码）
2. 史料编码：匹配到的脚注按序编为 M1, M2, M3...
3. 非史料排除：现代学者论著不编号、不统计
4. 正文引用符号识别
"""

import re


# --- 删除类：匹配到的 block.content 需删除 ---

# 匹配摘要段
PATTERN_01_001 = re.compile(r"^摘要[：:]")
# 用途：删除摘要段（content 以"摘要："或"摘要："开头）

# 匹配关键词段
PATTERN_01_002 = re.compile(r"^关键词[：:]")
# 用途：删除关键词段

# 匹配作者名行（标题后、摘要前的纯姓名行）
PATTERN_01_003 = re.compile(r"^[\u4e00-\u9fff]{2,4}(\s+[\u4e00-\u9fff]{2,4})*\*{0,2}$")
# 用途：删除作者名行（如"刘玉堂 钱明昊**"），仅含中文姓名+空格+可选星号

# 匹配机构行（括号内含大学/学院/研究中心等）
PATTERN_01_004 = re.compile(r"^[（(].*?(大学|学院|研究中心|研究所|研究院|实验室|系)")
# 用途：删除机构行（如"(华中师范大学国家文化产业研究中心，湖北 武汉 430079)"）

# 匹配基金项目脚注
PATTERN_01_005 = re.compile(r"^\*\s*基金项目")
# 用途：删除基金项目脚注（content 以"* 基金项目"或"* 基金项目"开头）

# 匹配作者简介脚注
PATTERN_01_006 = re.compile(r"^\*\*作者简介")
# 用途：删除作者简介脚注

# 匹配 DOI 编号
PATTERN_01_007 = re.compile(r"^DOI[:：]", re.IGNORECASE)
# 用途：删除 DOI 行

# 匹配中国知网水印
PATTERN_01_008 = re.compile(r"^中国知网\s*https?://")
# 用途：删除知网水印行

# 匹配页眉运行标题（■ 开头）
PATTERN_01_009 = re.compile(r"^■")
# 用途：删除运行页眉

# 匹配丛书名行
PATTERN_01_010 = re.compile(r"^宋史研究论丛")
# 用途：删除丛书名行

# 匹配纯页码（仅数字）
PATTERN_01_011 = re.compile(r"^\d{1,4}$")
# 用途：删除页码行


# --- 史料编码类：匹配到的脚注按序编为 M1, M2, M3... ---

# 匹配史料脚注——朝代标记型
# 规则：圈注号紧跟（朝代），如 ①（唐） ②（宋） ①（清）
PATTERN_01_020 = re.compile(r"^[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]\s*[（(](唐|宋|元|明|清|汉|晋|南北朝|五代)")
# 用途：识别史料脚注（圈注号+朝代括号），编为 M1, M2, ...

# 匹配史料脚注——经典书名型
# 规则：圈注号紧跟《书名》，如 ①《宋史》 ②《文献通考》
PATTERN_01_021 = re.compile(r"^[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]\s*《")
# 用途：识别史料脚注（圈注号+经典书名《》），编为 M1, M2, ...

# 史料脚注合并匹配（朝代型 OR 书名型）
PATTERN_01_022 = re.compile(
    r"^[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]\s*(?:[（(](?:唐|宋|元|明|清|汉|晋|南北朝|五代)|《)"
)
# 用途：一条正则合并 01_020 和 01_021，用于快速判定"是否为史料"


# --- 非史料排除类：匹配到的脚注不编号、不统计 ---

# 匹配非史料脚注——现代学者论著
# 规则：圈注号+空格+现代作者名（无朝代前缀），如 ② 华山： ③ 王子龙、郑志强：
PATTERN_01_030 = re.compile(r"^[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]\s+[\u4e00-\u9fff]")
# 用途：识别非史料脚注（现代学者论文/专著），不编号、不统计

# 匹配非史料脚注——现代学者述评型
# 规则：圈注号+空格+现代作者名+于/著/撰/编/辑 等现代学术用语
PATTERN_01_031 = re.compile(r"^[①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]\s+[\u4e00-\u9fff]{2,4}(于|著|撰|编|辑)")
# 用途：进一步确认非史料脚注（如"⑤ 孙洪升于《唐宋茶业经济》中统计..."）


# --- 正文引用符号识别 ---

# 匹配正文中的圈注引用符号
PATTERN_01_040 = re.compile(r"[①②③④⑤⑥⑦⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳]")
# 用途：识别正文中出现的 ①②③ 引用标记，用于后续论点→史料对应

# 匹配上标圈注引用（如 ^{⑩}）
PATTERN_01_041 = re.compile(r"\^\{([①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱⑲⑳])\}")
# 用途：识别 LaTeX 风格上标引用（如 ^{⑩}），常见于表格附近段落
